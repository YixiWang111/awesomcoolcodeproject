TOPICS_OVER_TIME_PNG = STRETCH_DIR / "topics_over_time.png"

# ------------------------------------------------- stretch goal: readability

# Flesch reading ease and Flesch-Kincaid grade are built on words-per-sentence and
# syllables-per-word. On a 5-word entry those ratios are meaningless - a single
# one-word sentence produces a real-looking number from nothing. Entries below
# these thresholds are still measured, but are excluded from the averages and
# reported as an excluded count.
MIN_READABLE_WORDS = 20
MIN_READABLE_SENTENCES = 2

# ------------------------------------------------- stretch goal: periods

# The two periods are split at the midpoint entry. Splitting at the midpoint of
# the corpus rather than at a calendar boundary keeps the two halves the same
# size, which is what makes the comparison meaningful at all.
PERIOD_LABELS = ("First half", "Second half")

# How many words to show in the between-period word change chart, per direction.
WORD_CHANGE_TOP_N = 12

# A word has to appear at least this many times across the whole corpus before its
# between-period change is worth showing. Without this the chart fills up with
# words that went from 1 use to 3: a large relative jump from nothing.
WORD_CHANGE_MIN_TOTAL = 8

# ------------------------------------------------- stretch goal: topics

# Colors for a heatmap need a single hue, light to dark. Reuses the sequential
# ramp already defined for the word cloud, so the project has one sequential scale.
TOPIC_HEATMAP_RAMP = ["#F2F6FC", "#CDE2FB", "#9EC5F4", "#6DA7EC", "#3987E5", "#256ABF", "#0D366B"]


# ------------------------------------------------------------------ plotting style

# Polarity is a diverging quantity: it has a real zero and two opposite poles, so
# it takes a diverging palette - two hues that read as opposite, plus a neutral
# gray for the midpoint. The obvious pick here would be green/red, and it is the
# wrong one: red-green is the single most common form of colour blindness, and the
# two poles collapse into each other. Blue/red was validated instead.
#
# Validated with the data-viz palette validator (OKLab dE x100):
#   poles  #2a78d6 / #e34948    CVD dE 21.6 (protanopia)   normal-vision dE 32.3
#   all checks PASS, both poles >= 3:1 contrast on the chart surface.
# The neutral gray is the documented diverging midpoint. It reads as "nothing",
# which is exactly its job - it is deliberately not a hue.
COLOUR_POSITIVE = "#2A78D6"   # blue pole
COLOUR_NEGATIVE = "#E34948"   # red pole
COLOUR_NEUTRAL = "#898781"    # midpoint gray: absence of polarity

# The smoothed trend is the finding, so it is drawn as emphasis in primary ink
# rather than in either pole colour - it must not read as "the trend is positive".
COLOUR_TREND = "#0B0B0B"
COLOUR_NEUTRAL_BAND = "#F0EFEC"   # diverging midpoint fill, very light

# Chart chrome: solid hairlines one shade off the surface. Never dashed.
COLOUR_SURFACE = "#FCFCFB"
COLOUR_GRID = "#E1E0D9"
COLOUR_AXIS = "#C3C2B7"
COLOUR_INK = "#0B0B0B"
COLOUR_INK_SECONDARY = "#52514E"
COLOUR_INK_MUTED = "#898781"

FIGURE_DPI = 150

# Sequential single hue for the word cloud. Word frequency is a magnitude, so the
# cloud takes one hue light-to-dark (darker = more frequent). A multi-coloured
# word cloud would be a rainbow ramp: it spends colour on nothing.
WORDCLOUD_RAMP = ["#CDE2FB", "#9EC5F4", "#6DA7EC", "#3987E5", "#256ABF", "#184F95", "#0D366B"]
WORDCLOUD_BG = "#FCFCFB"
