r"""
InkMirror - configuration
-------------------------
Single place for every path and constant the pipeline uses, so no other module
hard-codes a directory name. See README for how to point this at the real journal.
"""

from __future__ import annotations

from pathlib import Path

# ------------------------------------------------------------------ paths

PROJECT_ROOT = Path(__file__).parent

# The real corpus lives in `entries/`, one dated .txt file per entry.
# If it does not exist yet we fall back to the generated sample corpus so the
# pipeline can be run and demonstrated. Nothing else in the code needs to change
# when the real entries arrive - just create `entries/` and drop them in.
REAL_CORPUS_DIR = PROJECT_ROOT / "entries"
SAMPLE_CORPUS_DIR = PROJECT_ROOT / "entries_sample"

OUTPUT_DIR = PROJECT_ROOT / "output"

# Stretch-goal outputs go in their own folder. The pitch declares them as "if
# ahead", so keeping them physically separate keeps the assessed scope boundary
# visible: everything in output/ is the core deliverable, everything in
# output/stretch/ is optional extra.
STRETCH_DIR = OUTPUT_DIR / "stretch"


def corpus_dir() -> Path:
    """Return the directory the pipeline should read, preferring the real corpus."""
    if REAL_CORPUS_DIR.is_dir() and any(REAL_CORPUS_DIR.glob("*.txt")):
        return REAL_CORPUS_DIR
    return SAMPLE_CORPUS_DIR


def is_using_sample_corpus() -> bool:
    """True when we are running on placeholder data rather than the real journal."""
    return corpus_dir() == SAMPLE_CORPUS_DIR


def corpus_source() -> str:
    """Short machine-readable provenance tag, written into every CSV row.

    Every result file carries this as a column rather than a header comment, so
    that a single row copied out of a spreadsheet still says where it came from.
    Provenance that can be lost by copying is not provenance.
    """
    return "synthetic_sample" if is_using_sample_corpus() else "private_journal"


def corpus_source_description() -> str:
    """One-line human-readable provenance, for report headers."""
    if is_using_sample_corpus():
        return (
            "SYNTHETIC SAMPLE - generated placeholder data, not a real journal. "
            "Generated by make_sample_corpus.py from a scripted mood curve."
        )
    return "Private journal, analysed locally. No entry text left this machine."


# ------------------------------------------------------------------ analysis settings

# English only, as scoped in the project pitch.
LANGUAGE = "english"

# Tokens shorter than this are dropped before frequency counting: single letters
# and stray characters carry no signal about vocabulary habits.
MIN_TOKEN_LENGTH = 3

# How many words to keep in the frequency table and the word cloud.
TOP_N_WORDS = 50

# Window (in entries, not days) for the smoothed sentiment line on the timeline.
# Entries are irregularly spaced, so we smooth over entry index rather than time.
SMOOTHING_WINDOW = 21

# ------------------------------------------------------------------ output filenames

SENTIMENT_CSV = OUTPUT_DIR / "sentiment_scores.csv"
LEXICAL_CSV = OUTPUT_DIR / "lexical_stats.csv"
FREQUENCY_CSV = OUTPUT_DIR / "word_frequencies.csv"
TIMELINE_PNG = OUTPUT_DIR / "sentiment_timeline.png"
WORDCLOUD_PNG = OUTPUT_DIR / "wordcloud.png"
VALIDATION_PNG = OUTPUT_DIR / "validation.png"

# ------------------------------------------------------ stretch goal outputs

READABILITY_CSV = STRETCH_DIR / "readability_scores.csv"
PERIOD_SUMMARY_CSV = STRETCH_DIR / "period_summary.csv"
TOPIC_CSV = STRETCH_DIR / "topic_tags.csv"
PERIOD_COMPARISON_PNG = STRETCH_DIR / "period_comparison.png"
